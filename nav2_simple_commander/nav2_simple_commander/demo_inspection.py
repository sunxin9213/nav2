# RFID 传感器沿预定义巡检路线（一组航点）依次停靠，
# 在每个航点采集库存信息，结束后返回起点。
# 使用 BasicNavigator 的 followWaypoints（航点跟随）+ goToPose（返航）。
# ============================================================================

from copy import deepcopy

from geometry_msgs.msg import PoseStamped
from nav2_simple_commander.robot_navigator import BasicNavigator, TaskResult
import rclpy

"""
Basic stock inspection demo. In this demonstration, the expectation
is that there are cameras or RFID sensors mounted on the robots
collecting information about stock quantity and location.
基础库存巡检演示：机器人搭载相机/RFID 沿路线采集库存数量与位置信息。
"""


def main():
    # 初始化 rclpy 并创建导航器
    rclpy.init()

    navigator = BasicNavigator()

    # Inspection route, probably read in from a file for a real application
    # from either a map or drive and repeat.
    # 巡检路线（实际应用中通常从地图文件或"示教重放"中读取）
    inspection_route = [
        [3.461, -0.450],
        [5.531, -0.450],
        [3.461, -2.200],
        [5.531, -2.200],
        [3.661, -4.121],
        [5.431, -4.121],
        [3.661, -5.850],
        [5.431, -5.800]]

    # Set our demo's initial pose
    # 设置演示初始位姿
    initial_pose = PoseStamped()
    initial_pose.header.frame_id = 'map'
    initial_pose.header.stamp = navigator.get_clock().now().to_msg()
    initial_pose.pose.position.x = 3.45
    initial_pose.pose.position.y = 2.15
    initial_pose.pose.orientation.z = 1.0
    initial_pose.pose.orientation.w = 0.0
    navigator.setInitialPose(initial_pose)

    # Wait for navigation to fully activate
    # 阻塞等待 Nav2 完全激活
    navigator.waitUntilNav2Active()

    # Send our route
    # 把巡检路线转换为位姿列表并发送航点跟随任务
    inspection_points = []
    inspection_pose = PoseStamped()
    inspection_pose.header.frame_id = 'map'
    inspection_pose.header.stamp = navigator.get_clock().now().to_msg()
    inspection_pose.pose.orientation.z = 1.0
    inspection_pose.pose.orientation.w = 0.0
    for pt in inspection_route:
        inspection_pose.pose.position.x = pt[0]
        inspection_pose.pose.position.y = pt[1]
        # deepcopy：消息对象为引用，必须深拷贝才能保存不同航点
        inspection_points.append(deepcopy(inspection_pose))
    navigator.followWaypoints(inspection_points)

    # Do something during our route (e.x. AI to analyze stock information or upload to the cloud)
    # Simply the current waypoint ID for the demonstation
    # 跟随期间可执行应用逻辑（如 AI 分析库存并上传云端）；
    # 演示中仅打印当前航点进度
    i = 0
    while not navigator.isTaskComplete():
        i += 1
        feedback = navigator.getFeedback()
        if feedback and i % 5 == 0:
            print('Executing current waypoint: ' +
                  str(feedback.current_waypoint + 1) + '/' + str(len(inspection_points)))

    # 巡检结果输出
    result = navigator.getResult()
    if result == TaskResult.SUCCEEDED:
        print('Inspection of shelves complete! Returning to start...')
    elif result == TaskResult.CANCELED:
        print('Inspection of shelving was canceled. Returning to start...')
    elif result == TaskResult.FAILED:
        print('Inspection of shelving failed! Returning to start...')

    # go back to start
    # 巡检结束：导航返回起点（刷新时间戳后发送单点导航）
    initial_pose.header.stamp = navigator.get_clock().now().to_msg()
    navigator.goToPose(initial_pose)
    while not navigator.isTaskComplete():
        pass

    exit(0)


if __name__ == '__main__':
    main()



